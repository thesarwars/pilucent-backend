"""Admin for recurring templates, their lines, and the occurrence ledger.

Loading notes — these models are unusually FK-heavy (25 across the three), so a
naive admin is very slow:

* Every FK uses ``raw_id_fields``. Without it each change form renders a
  ``<select>`` holding *every* customer, supplier, product, account, tax rate and
  warehouse in the database — one full-table query per FK, on every page load.
* List pages ``select_related`` exactly the columns they display, so a page of
  100 rows costs one query rather than one per row per FK.
* Line counts and occurrence counts are annotated in SQL rather than counted per
  row in Python.
* ``show_full_result_count`` is off: the unfiltered ``COUNT(*)`` Django runs to
  render "99 results (1,234 total)" is pure cost on a growing ledger.
"""

from django.contrib import admin
from django.db.models import Count

from .models import RecurringOccurrence, RecurringTemplate, RecurringTemplateLine


class RecurringTemplateLineInline(admin.TabularInline):
    """Lines edited in the context of their template."""

    model = RecurringTemplateLine
    extra = 0
    fields = [
        "position",
        "line_type",
        "product",
        "charter_account",
        "description",
        "quantity",
        "rate",
        "amount",
        "tax",
        "customer",
        "supplier",
        "payment_method",
        "reference_number",
    ]
    raw_id_fields = [
        "product",
        "charter_account",
        "tax",
        "customer",
        "supplier",
        "payment_method",
    ]
    ordering = ["position", "id"]

    def get_queryset(self, request):
        # The inline renders each line's related objects; fetch them with the
        # lines rather than one query per row.
        return (
            super()
            .get_queryset(request)
            .select_related("product", "charter_account", "tax")
        )


