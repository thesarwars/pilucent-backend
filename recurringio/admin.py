@admin.register(RecurringOccurrence)
class RecurringOccurrenceAdmin(admin.ModelAdmin):
    """The run history: one row per (template, date) the job has acted on.

    This doubles as the idempotency ledger — ``unique(template,
    occurrence_date)`` is what stops a retried run double-billing — so rows are
    read-only here. Deleting one would let that date fire a second time.
    """

    list_display = [
        "occurrence_date",
        "template",
        "txn_type",
        "status",
        "generated_document",
        "resolved_at",
        "short_error",
    ]
    list_filter = ["status", "template__txn_type", "occurrence_date"]
    search_fields = ["template__name", "error_detail"]
    date_hierarchy = "occurrence_date"
    ordering = ["-occurrence_date", "-created_at"]
    raw_id_fields = [
        "company",
        "template",
        "generated_purchase",
        "generated_sale",
        "generated_credit_note",
        "generated_deposit",
    ]
    readonly_fields = [
        "uid",
        "template",
        "occurrence_date",
        "status",
        "reminded_at",
        "resolved_at",
        "error_detail",
        "generated_purchase",
        "generated_sale",
        "generated_credit_note",
        "generated_deposit",
        "company",
        "created_at",
        "updated_at",
    ]
    list_per_page = 50
    show_full_result_count = False

    def get_queryset(self, request):
        # Every column this list renders comes off a related object, so all of
        # them are joined -- see the note on the template admin.
        return (
            super()
            .get_queryset(request)
            .select_related(
                "template",
                "generated_purchase",
                "generated_sale",
                "generated_credit_note",
                "generated_deposit",
            )
        )

    def has_add_permission(self, request):
        # Occurrences are written by the generation job. A hand-made row would
        # silently prevent that date from ever firing.
        return False

    def has_change_permission(self, request, obj=None):
        return False

    @admin.display(description="Type", ordering="template__txn_type")
    def txn_type(self, obj):
        return obj.template.txn_type

    @admin.display(description="Generated")
    def generated_document(self, obj):
        """Whichever of the four document shapes this firing produced."""
        for label, document in (
            ("Purchase", obj.generated_purchase),
            ("Sale", obj.generated_sale),
            ("Credit note", obj.generated_credit_note),
            ("Deposit", obj.generated_deposit),
        ):
            if document is not None:
                return f"{label}: {document.uid}"
        return "—"

    @admin.display(description="Error")
    def short_error(self, obj):
        if not obj.error_detail:
            return ""
        return (obj.error_detail[:80] + "…") if len(obj.error_detail) > 80 else (
            obj.error_detail
        )
