    def get_queryset(self, request):
        """Join what the list renders and count lines in SQL.

        The joins live here rather than in ``list_select_related`` because that
        is only applied by the changelist — anything else using this queryset
        (an action, an export) would fall back to one query per row.
        """
        return (
            super()
            .get_queryset(request)
            .select_related("supplier", "customer")
            .annotate(_line_count=Count("lines"))
        )

    @admin.display(description="Party", ordering="supplier__display_name")
    def party(self, obj):
        """The counterparty, whichever side this type uses.

        A DEPOSIT has neither — its payer lives on the fund rows.
        """
        party = obj.supplier or obj.customer
        if party is None:
            return "—"
        return (
            getattr(party, "display_name", None)
            or f"{party.first_name} {party.last_name or ''}".strip()
        )

    @admin.display(description="Lines", ordering="_line_count")
    def line_count(self, obj):
        return obj._line_count


